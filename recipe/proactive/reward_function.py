def _next_url():
    global _URL_PID, _URL_INDEX
    with _URL_LOCK:
        if os.getpid() != _URL_PID:
            _URL_PID = os.getpid()
            _URL_INDEX = _URL_PID % len(URLS)
        url = URLS[_URL_INDEX % len(URLS)]
        _URL_INDEX += 1
    return url


def _get_session():
    session = getattr(_SESSION_LOCAL, "session", None)
    if session is None:
        session = requests.Session()
        session.trust_env = TRUST_ENV
        _SESSION_LOCAL.session = session
    return session


