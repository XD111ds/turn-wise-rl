def send_request(model_input, instruction, model=MODEL, answer_kind="similarity"):
    if "Qwen3" in model:
        model_input += "/no_think"
    data = {
        "model": model,
        "messages": [
            {"role": "system", "content": instruction},
            {"role": "user", "content": model_input},
        ],
        "temperature": 0.0,
        "top_p": 1.0,
        "max_tokens": MAX_TOKENS,
        "stream": False,
    }
    if "gemini-2.5" in model:
        data["reasoning_effort"] = "low"
    if API_KEY is not None:
        headers = {
            "Authorization": f"Bearer {API_KEY}",
            "Content-Type": "application/json",
        }
    else:
        headers = None
    import sys
    from recipe.proactive.judge_client import validated_request

    return validated_request(sys.modules[__name__], data, headers, answer_kind)


def calculate_similarity_score(time, question, pred, gold):
    model_input = (
        f"Question: {question}\nGround Truth Answer: {gold}\nPredicted Answer: {pred}\n"
    )
    model_output = send_request(
        model_input, similarity_instruction[MAX_SCORES], model=MODEL
    )
    if model_output in [str(i) for i in range(1, MAX_SCORES + 1)]:
        score = int(model_output) - 1
    else:
        score = None
    return (time, score)


def calculate_is_repetition(time, previous_sents, pred_sent):
    model_input = f"Previous Turns: {previous_sents}\nNew Turn: {pred_sent}\n"
    model_output = send_request(
        model_input,
        repetition_instruction,
        model=MODEL_REPETITION,
        answer_kind="repetition",
    )
    normalized = (model_output or "").lower().strip()
    res = True if normalized == "yes" else False if normalized == "no" else None
    return (time, res)


def calculate_have_common_prefix(time, previous_sents, pred_sent):
    for prev_sent in previous_sents:
        common_prefix = os.path.commonprefix([prev_sent, pred_sent])
        if len(common_prefix) >= COMMON_PREFIX_THRES:
            return (time, 1)
    return (time, 0)


